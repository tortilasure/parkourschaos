let current: Lang = "en";
const listeners = new Set<() => void>();

export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "en";
  const l = (navigator.language || "en").slice(0, 2).toLowerCase();
  if (l === "de") return "de";
  if (l === "ru" || l === "uk" || l === "be" || l === "kk") return "ru";
  return "en";
}
export function getLang(): Lang { return current; }
export function setLang(l: Lang) {
  if (l === current) return;
  current = l;
  for (const f of listeners) f();
}
export function onLangChange(f: () => void) { listeners.add(f); return () => listeners.delete(f); }

export function t(key: string, vars?: Record<string, string | number>): string {
  const row = D[key];
  let s = row ? row[IDX[current]] || row[1] : key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
export function tOpt(key: string, vars?: Record<string, string | number>): string {
  return D[key] ? t(key, vars) : "";
}
